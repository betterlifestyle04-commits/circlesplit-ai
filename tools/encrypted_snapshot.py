"""Operator-only encrypted CircleSplit SQLite Sandbox backup container.

No endpoint, no live restore, no remote uploads, no PayPal calls.
The secret lives in a separate private passphrase file, NEVER in process args.
Requires: pip install -r requirements-ops.txt

  python tools/encrypted_snapshot.py keygen --output /private/key.passphrase
  python tools/encrypted_snapshot.py seal --source /path/demo.sqlite3 \
      --output /private/demo-20261105.csb --key-file /private/key.passphrase
  python tools/encrypted_snapshot.py verify --bundle /private/demo-20261105.csb \
      --key-file /private/key.passphrase
  python tools/encrypted_snapshot.py drill --bundle /private/demo-20261105.csb \
      --key-file /private/key.passphrase

Encrypts a verified online snapshot *and its manifest* with streaming AES-256
GCM. Keys are derived from 48 randomly generated bytes via scrypt and unique
salt; the nonce is independently random per archive. Both header and contents
are authenticated. Only an isolated mode-0700 temporary folder contains raw
SQLite data, and is removed before an encrypted archive is published.

This does NOT make a hosted ephemeral DB durable; the operator must preserve
archives offsite and keep keys separately. Encryption does not attest PayPal.
"""
from __future__ import annotations

import argparse
from contextlib import contextmanager
import json
import os
from pathlib import Path
import secrets
import stat
import struct
import sys
import tempfile

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from tools import sqlite_snapshot

MAGIC = b"CSBUP01\x00"
HEADER = struct.Struct(">8s16s12sQI")
TAG_LENGTH = 16
MAX_MANIFEST = sqlite_snapshot.MAX_MANIFEST_BYTES
MAX_DATABASE = sqlite_snapshot.MAX_BYTES
BLOCK = 1024 * 1024
PASSPHRASE_BYTES_MIN = 20
PASSPHRASE_BYTES_MAX = 1024


class ArchiveError(Exception):
    """Non-secret operator-visible failure."""


def _absolute(path: str | Path) -> Path:
    return Path(path).expanduser().absolute()


def _secure_directory(path: Path) -> None:
    if not path.is_dir() or path.is_symlink():
        raise ArchiveError("Create a private destination directory before running this command.")
    if os.name == "posix":
        mode = stat.S_IMODE(path.stat().st_mode)
        if path.stat().st_uid != os.getuid() or mode & 0o077:
            raise ArchiveError("Private destination directory must be user-owned, mode 0700.")


def _destination(path: str | Path, extension: str) -> Path:
    result = _absolute(path)
    if result.suffix != extension:
        raise ArchiveError("Unexpected output filename extension for encrypted archive/key.")
    _secure_directory(result.parent)
    if result.exists() or result.is_symlink():
        raise ArchiveError("Refusing to overwrite existing confidential output.")
    return result


def _read_key_file(filename: str | Path) -> bytes:
    path = _absolute(filename)
    if path.is_symlink() or not path.is_file():
        raise ArchiveError("Passphrase file must exist and must not be a symlink.")
    if os.name == "posix" and (
        path.stat().st_uid != os.getuid() or stat.S_IMODE(path.stat().st_mode) & 0o077
    ):
        raise ArchiveError("Passphrase file must be user-owned and permission 0600.")
    if not 20 <= path.stat().st_size <= PASSPHRASE_BYTES_MAX + 2:
        raise ArchiveError("Passphrase file must contain 20–1024 private random bytes.")
    with path.open("rb") as stream:
        secret = stream.read(PASSPHRASE_BYTES_MAX + 3).rstrip(b"\r\n")
    if not PASSPHRASE_BYTES_MIN <= len(secret) <= PASSPHRASE_BYTES_MAX:
        raise ArchiveError("Passphrase file length is outside the supported range.")
    return secret


def _derive(secret: bytes, salt: bytes) -> bytes:
    return Scrypt(salt=salt, length=32, n=1 << 15, r=8, p=1).derive(secret)


def keygen(path: str | Path) -> None:
    """Create a strong 48-byte random secret, no overwrite or stdout exposure."""
    target = _destination(path, ".passphrase")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    try:
        fd = os.open(str(target), flags, 0o600)
        with os.fdopen(fd, "wb") as out:
            if hasattr(os, "fchmod"):
                os.fchmod(out.fileno(), 0o600)
            out.write(secrets.token_urlsafe(48).encode("ascii") + b"\n")
            out.flush()
            os.fsync(out.fileno())
    except OSError as exc:
        raise ArchiveError("Unable to create a new private passphrase file.") from exc


def _require_bundle(filename: str | Path) -> Path:
    path = _absolute(filename)
    if path.is_symlink() or not path.is_file() or path.suffix != ".csb":
        raise ArchiveError("Encrypted archive must be an existing regular .csb file.")
    if not HEADER.size + TAG_LENGTH + 100 <= path.stat().st_size <= (
        HEADER.size + MAX_DATABASE + MAX_MANIFEST + TAG_LENGTH
    ):
        raise ArchiveError("Encrypted archive has an unsupported size.")
    return path


def _seal_stream(raw_db: Path, raw_manifest: Path, output: Path, secret: bytes) -> None:
    """Generate authenticated ciphertext and publish without overwriting."""
    size_db = raw_db.stat().st_size
    size_manifest = raw_manifest.stat().st_size
    if not (100 <= size_db <= MAX_DATABASE and 1 <= size_manifest <= MAX_MANIFEST):
        raise ArchiveError("Snapshot is too large for the encrypted archive format.")
    salt = os.urandom(16)
    nonce = os.urandom(12)
    header = HEADER.pack(MAGIC, salt, nonce, size_db, size_manifest)
    cipher = Cipher(algorithms.AES(_derive(secret, salt)), modes.GCM(nonce))
    encryptor = cipher.encryptor()
    encryptor.authenticate_additional_data(header)
    fd, temp_name = tempfile.mkstemp(prefix=".circle-encrypt-", suffix=".part",
                                     dir=str(output.parent))
    pending = Path(temp_name)
    try:
        with os.fdopen(fd, "wb") as stream:
            if hasattr(os,"fchmod"):
                os.fchmod(stream.fileno(), 0o600)
            stream.write(header)
            for item in (raw_db, raw_manifest):
                with item.open("rb") as plain:
                    while chunk := plain.read(BLOCK):
                        stream.write(encryptor.update(chunk))
            stream.write(encryptor.finalize())
            stream.write(encryptor.tag)
            stream.flush()
            os.fsync(stream.fileno())
        # Atomic, never overwrite an archive even on a concurrent invocation.
        os.link(str(pending), str(output))
    except OSError as exc:
        raise ArchiveError("Could not safely publish the encrypted archive.") from exc
    finally:
        pending.unlink(missing_ok=True)


def seal(source: str | Path, output: str | Path, key_file: str | Path) -> dict:
    """Snapshot an accessible local DB, encrypt, then delete staged plaintext."""
    dest = _destination(output, ".csb")
    secret = _read_key_file(key_file)
    try:
        with tempfile.TemporaryDirectory(prefix=".circle-plaintext-", dir=str(dest.parent)) as area:
            scratch = Path(area) / "staged.sqlite3"
            manifest = sqlite_snapshot.create(source, scratch)
            raw_sidecar = Path(str(scratch) + ".manifest.json")
            # The source was transactionally copied & verified before encryption.
            if sqlite_snapshot.verify(scratch) != manifest:
                raise ArchiveError("Staged SQLite snapshot verification failed.")
            _seal_stream(scratch, raw_sidecar, dest, secret)
        return manifest
    except sqlite_snapshot.SnapshotError as exc:
        raise ArchiveError("Unable to create a consistent private SQLite snapshot.") from exc


def _decrypt_bundle(archive: Path, key: bytes, scratch: Path) -> Path:
    """Decrypt only inside a private temp dir; authenticate before parsing SQLite."""
    archive = _require_bundle(archive)
    with archive.open("rb") as source:
        header = source.read(HEADER.size)
        if len(header) != HEADER.size:
            raise ArchiveError("Invalid encrypted archive header.")
        magic, salt, nonce, db_bytes, manifest_bytes = HEADER.unpack(header)
        if magic != MAGIC or not (100 <= db_bytes <= MAX_DATABASE) or not (
            1 <= manifest_bytes <= MAX_MANIFEST
        ):
            raise ArchiveError("Encrypted archive header is invalid.")
        if archive.stat().st_size != HEADER.size + db_bytes + manifest_bytes + TAG_LENGTH:
            raise ArchiveError("Encrypted archive length does not match its header.")
        source.seek(-TAG_LENGTH, 2)
        tag = source.read(TAG_LENGTH)
        source.seek(HEADER.size)
        decryptor = Cipher(algorithms.AES(_derive(key, salt)), modes.GCM(nonce, tag)).decryptor()
        decryptor.authenticate_additional_data(header)

        output = scratch / "extracted.sqlite3"
        sidecar = Path(str(output) + ".manifest.json")
        remaining_db = db_bytes
        remaining_cipher = db_bytes + manifest_bytes
        with output.open("xb") as db_out, sidecar.open("xb") as meta_out:
            output.chmod(0o600)
            sidecar.chmod(0o600)
            try:
                while remaining_cipher:
                    chunk = source.read(min(BLOCK, remaining_cipher))
                    if not chunk:
                        raise ArchiveError("Encrypted archive data is truncated.")
                    remaining_cipher -= len(chunk)
                    clear = decryptor.update(chunk)
                    first, second = clear[:remaining_db], clear[remaining_db:]
                    db_out.write(first)
                    meta_out.write(second)
                    remaining_db -= len(first)
                tail = decryptor.finalize()
                if tail:
                    raise ArchiveError("Unexpected archive authentication trailer.")
            except InvalidTag as exc:
                raise ArchiveError("Decryption authentication failed: key or archive is invalid.") from exc
        return output


def _open_and_check(bundle: str | Path, key_file: str | Path, operation: str) -> dict:
    secret = _read_key_file(key_file)
    archive = _require_bundle(bundle)
    # Explicitly private scratch even when archive was copied from elsewhere.
    with tempfile.TemporaryDirectory(prefix="circle-decrypt-") as folder:
        scratch=Path(folder)
        extracted=_decrypt_bundle(archive, secret, scratch)
        try:
            if operation == "verify":
                return sqlite_snapshot.verify(extracted)
            if operation == "drill":
                return sqlite_snapshot.drill(extracted)
            raise ArchiveError("Unsupported encrypted archive operation.")
        except sqlite_snapshot.SnapshotError as exc:
            raise ArchiveError("Decrypted database failed offline integrity/recovery review.") from exc


def verify(bundle: str | Path, key_file: str | Path) -> dict:
    return _open_and_check(bundle, key_file, "verify")


def drill(bundle: str | Path, key_file: str | Path) -> dict:
    return _open_and_check(bundle, key_file, "drill")


def main(argv: list[str] | None = None) -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    cmd=parser.add_subparsers(dest="action",required=True)
    gen=cmd.add_parser("keygen",help="Write a random private key file (not printed)")
    gen.add_argument("--output",required=True)
    sealcmd=cmd.add_parser("seal",help="Create consistent encrypted snapshot")
    sealcmd.add_argument("--source",required=True)
    sealcmd.add_argument("--output",required=True)
    sealcmd.add_argument("--key-file",required=True)
    for action in ("verify","drill"):
        entry=cmd.add_parser(action,help="Decrypt temporarily for read-only checks")
        entry.add_argument("--bundle",required=True)
        entry.add_argument("--key-file",required=True)
    args=parser.parse_args(argv)
    try:
        if args.action=="keygen":
            keygen(args.output)
            print(json.dumps({"status":"PASS","operation":"keygen",
                              "notice":"Secret generated to a private file; store separately from encrypted backups."}))
            return 0
        if args.action=="seal":
            data=seal(args.source,args.output,args.key_file)
        elif args.action=="verify":
            data=verify(args.bundle,args.key_file)
        else:
            data=drill(args.bundle,args.key_file)
    except (ArchiveError, OSError, ValueError) as exc:
        print("FAILED: "+str(exc),file=sys.stderr)
        return 2
    review=data.get("ledger_review")
    anomalous=bool(review and review["status"]=="needs_review")
    out={"status":"NEEDS_REVIEW" if anomalous else "PASS",
         "operation":args.action, "database_epoch_prefix":data["database_epoch"][:12],
         "counts":data["counts"],
         "notice":"Encrypted operator-only snapshot. No live restore, provider settlement or automatic offsite copy."}
    if review:
        out["local_ledger_review"]=review
    print(json.dumps(out,sort_keys=True))
    return 3 if anomalous else 0


if __name__=="__main__":
    raise SystemExit(main())
